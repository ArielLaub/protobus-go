func run(t *testing.T, files []*descriptorpb.FileDescriptorProto, generate string) (*pluginpb.CodeGeneratorResponse, error) {
	t.Helper()
	req := &pluginpb.CodeGeneratorRequest{
		FileToGenerate: []string{generate},
		Parameter:      proto.String("paths=source_relative"),
		ProtoFile:      files,
	}
	p, err := protogen.Options{}.New(req)
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range p.Files {
		if f.Generate {
			if _, err := GenerateFile(p, f); err != nil {
				return nil, err
			}
		}
	}
	return p.Response(), nil
}

func TestGeneratedCodeIsCurrent(t *testing.T) {
	// internal/gentest is generated by this generator; regenerating it must
	// change nothing, or the checked-in bindings are stale.
	resp, err := run(t, []*descriptorpb.FileDescriptorProto{
		protodesc.ToFileDescriptorProto(pbtypes.File_protobus_types_proto),
		protodesc.ToFileDescriptorProto(gentest.File_gentest_proto),
	}, "gentest.proto")
	if err != nil {
		t.Fatal(err)
	}
	if resp.Error != nil {
		t.Fatal(*resp.Error)
	}
	if len(resp.File) != 1 || resp.File[0].GetName() != "gentest_protobus.pb.go" {
		t.Fatalf("files %v", resp.File)
	}
	want, err := os.ReadFile("../gentest/gentest_protobus.pb.go")
	if err != nil {
		t.Fatal(err)
	}
	// Leading comments are not part of descriptors built from the compiled
	// registry, so compare the code with comment lines removed.
	if stripComments(resp.File[0].GetContent()) != stripComments(string(want)) {
		t.Fatalf("internal/gentest is stale; run go generate ./internal/gentest\n--- generated ---\n%s", resp.File[0].GetContent())
	}
}

func stripComments(s string) string {
	var out []string
	for _, line := range strings.Split(s, "\n") {
		if t := strings.TrimSpace(line); strings.HasPrefix(t, "//") || t == "" {
			continue
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

func file(name string, methods ...*descriptorpb.MethodDescriptorProto) *descriptorpb.FileDescriptorProto {
	return &descriptorpb.FileDescriptorProto{
		Name:    proto.String(name),
		Package: proto.String("P"),
		Syntax:  proto.String("proto3"),
		Options: &descriptorpb.FileOptions{GoPackage: proto.String("example.com/p")},
		MessageType: []*descriptorpb.DescriptorProto{
			{Name: proto.String("M")},
		},
		Service: []*descriptorpb.ServiceDescriptorProto{{Name: proto.String("S"), Method: methods}},
	}
}

func method(name string, clientStream, serverStream bool) *descriptorpb.MethodDescriptorProto {
	return &descriptorpb.MethodDescriptorProto{
		Name: proto.String(name), InputType: proto.String(".P.M"), OutputType: proto.String(".P.M"),
		ClientStreaming: proto.Bool(clientStream), ServerStreaming: proto.Bool(serverStream),
	}
}

func TestClientStreamingIsRefused(t *testing.T) {
	_, err := run(t, []*descriptorpb.FileDescriptorProto{file("p.proto", method("up", true, false))}, "p.proto")
	if err == nil || !strings.Contains(err.Error(), "client streaming") {
		t.Fatalf("got %v", err)
	}
}

func TestGoNameClashIsRefused(t *testing.T) {
	_, err := run(t, []*descriptorpb.FileDescriptorProto{file("p.proto", method("get_x", false, false), method("getX", false, false))}, "p.proto")
	if err == nil || !strings.Contains(err.Error(), "Go name") {
		t.Fatalf("got %v", err)
	}
}

func TestFileWithoutServicesGeneratesNothing(t *testing.T) {
	f := file("p.proto")
	f.Service = nil
	resp, err := run(t, []*descriptorpb.FileDescriptorProto{f}, "p.proto")
	if err != nil || len(resp.File) != 0 {
		t.Fatalf("got %v %v", resp.File, err)
	}
}

func TestStreamingOnlyServiceImportsNoProto(t *testing.T) {
	resp, err := run(t, []*descriptorpb.FileDescriptorProto{file("p.proto", method("watch", false, true))}, "p.proto")
	if err != nil {
		t.Fatal(err)
	}
	src := resp.File[0].GetContent()
	if strings.Contains(src, `"google.golang.org/protobuf/proto"`) || !strings.Contains(src, `"iter"`) {
		t.Fatalf("import set:\n%s", src)
	}
}

func TestUnaryOnlyServiceImportsNoIter(t *testing.T) {
	resp, err := run(t, []*descriptorpb.FileDescriptorProto{file("p.proto", method("get", false, false))}, "p.proto")
	if err != nil {
		t.Fatal(err)
	}
	if src := resp.File[0].GetContent(); strings.Contains(src, `"iter"`) {
		t.Fatalf("import set:\n%s", src)
	}
}
